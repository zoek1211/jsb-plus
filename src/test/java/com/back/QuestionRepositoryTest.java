package com.back;

import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.test.context.ActiveProfiles;

import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;

// QuestionRepository 의 동작을 검사하는 테스트 클래스.
// 교재는 SbbApplicationTests 한 곳에 모든 테스트를 넣지만, 강사 방식(14163 15강)대로 검사 대상별로 테스트 클래스를 나눈다.
// Tests for QuestionRepository.
// The book puts every test in SbbApplicationTests; following the instructor (14163 lecture 15), we split test classes by what they test.
//
// "test" 프로필 → 메모리 DB + TestInitData 가 샘플 질문 2개를 미리 저장해 둔다 (006-02).
// "test" profile → in-memory database, and TestInitData has already saved 2 sample questions (006-02).
@ActiveProfiles("test")
@SpringBootTest
class QuestionRepositoryTest {

    // 스프링이 만든 리포지터리 구현 객체를 주입받는다.
    // Injects the repository implementation that Spring generated.
    @Autowired
    private QuestionRepository questionRepository;

    @Test
    @DisplayName("findAll: 샘플 질문 2개를 모두 조회한다")
    void t1() {
        // findAll() → SELECT * FROM question. 결과는 Question 객체들의 List.
        // findAll() → SELECT * FROM question. The result is a List of Question objects.
        List<Question> all = questionRepository.findAll();

        // assertEquals(기대값, 실제값): 두 값이 다르면 테스트 실패. 기대값을 먼저 쓰는 것이 JUnit 의 약속이다.
        // TestInitData 가 2개를 저장했으므로 2개여야 한다.
        // assertEquals(expected, actual): the test fails if they differ. JUnit's convention is expected first.
        // TestInitData saved 2, so there must be 2.
        assertEquals(2, all.size());

        // 첫 번째로 저장한 질문의 제목 확인. getSubject() 는 @Getter 가 만들어 준 메서드다.
        // Check the subject of the first saved question. getSubject() was generated by @Getter.
        Question q = all.get(0);
        assertEquals("sbb가 무엇인가요?", q.getSubject());
    }
}
