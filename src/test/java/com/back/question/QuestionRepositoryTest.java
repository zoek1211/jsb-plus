package com.back.question;

import com.back.answer.Answer;
import com.back.answer.AnswerRepository;

import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.transaction.annotation.Transactional;

import java.time.LocalDateTime;
import java.util.List;

// AssertJ: 테스트 검사(assertion)를 문장처럼 읽히게 써 주는 라이브러리. 테스트 스타터에 이미 포함되어 있다.
// assertThat(실제값).isEqualTo(기대값) — 실제값이 항상 assertThat 안에 들어가므로 JUnit assertEquals 처럼 순서를 헷갈릴 일이 없다.
// AssertJ: a library that makes test checks (assertions) read like sentences. Already included in the test starter.
// assertThat(actual).isEqualTo(expected): the actual value always goes inside assertThat, so there's no
// "which argument comes first?" confusion like with JUnit's assertEquals.
import static org.assertj.core.api.Assertions.assertThat;

// QuestionRepository 의 동작을 검사하는 테스트 클래스.
// 교재는 SbbApplicationTests 한 곳에 모든 테스트를 넣지만, 강사 방식(14163 15강)대로 검사 대상별로 테스트 클래스를 나눈다.
// Tests for QuestionRepository.
// The book puts every test in SbbApplicationTests; following the instructor (14163 lecture 15), we split test classes by what they test.
//
// "test" 프로필 → 메모리 DB + TestInitData 가 샘플 질문 2개를 미리 저장해 둔다 (006-02).
// "test" profile → in-memory database, and TestInitData has already saved 2 sample questions (006-02).
@ActiveProfiles("test")
@SpringBootTest
// 클래스에 붙인 @Transactional: 이 클래스의 "모든" 테스트 메서드를 각각 하나의 트랜잭션 안에서 실행한다 (14163 25강).
// 1) 테스트가 끝나면 자동 롤백 → 수정·삭제 테스트가 다른 테스트에 영향을 주지 않는다 (008-01 에서 확인).
// 2) 테스트 내내 DB 연결(세션)이 열려 있음 → LAZY 로딩(question.getAnswers())이 정상 동작한다.
//    빼면 t11 이 LazyInitializationException "... (no session)" 으로 실패한다 (009-03 에서 확인).
// 그래서 메서드마다 붙어 있던 @Transactional 은 지웠다.
// @Transactional on the class: runs "every" test method in this class inside its own transaction (14163 lecture 25).
// 1) Auto-rollback when each test ends → update/delete tests don't affect other tests (seen in 008-01).
// 2) The database connection (session) stays open for the whole test → LAZY loading (question.getAnswers()) works.
//    Without it, t11 fails with LazyInitializationException "... (no session)" (seen in 009-03).
// That's why the per-method @Transactional annotations were removed.
@Transactional
class QuestionRepositoryTest {

    // 스프링이 만든 리포지터리 구현 객체를 주입받는다.
    // Injects the repository implementation that Spring generated.
    @Autowired
    private QuestionRepository questionRepository;

    // 답변 저장·조회 테스트용 리포지터리.
    // Repository used by the answer save/read tests.
    @Autowired
    private AnswerRepository answerRepository;

    @Test
    @DisplayName("findAll: 샘플 질문 2개를 모두 조회한다")
    void t1() {
        // findAll() → SELECT * FROM question. 결과는 Question 객체들의 List.
        // findAll() → SELECT * FROM question. The result is a List of Question objects.
        List<Question> questions = questionRepository.findAll();

        // hasSize(2): "목록의 크기가 2개인가?" TestInitData 가 2개를 저장했으므로 2개여야 한다.
        // 실패하면 AssertJ는 기대 크기·실제 크기와 함께 목록 내용까지 보여준다.
        // hasSize(2): "does the list have 2 elements?" TestInitData saved 2, so there must be 2.
        // On failure, AssertJ prints the expected and actual size along with the list's contents.
        assertThat(questions).hasSize(2);

        // 첫 번째로 저장한 질문의 제목 확인. getSubject() 는 @Getter 가 만들어 준 메서드다.
        // isEqualTo: "기대값과 같은가?"
        // Check the subject of the first saved question. getSubject() was generated by @Getter.
        // isEqualTo: "is it equal to the expected value?"
        Question question = questions.get(0);
        assertThat(question.getSubject()).isEqualTo("sbb가 무엇인가요?");
    }

    @Test
    @DisplayName("findById: id 1번 질문을 조회한다")
    void t2() {
        // findById(1) → SELECT ... WHERE id = 1.
        // 결과가 없을 수도 있으므로 null 대신 Optional(값이 있거나 비어 있는 상자)을 돌려준다.
        // orElseThrow(): 상자에 값이 있으면 꺼내고, 비어 있으면 예외(NoSuchElementException)를 던진다 → 테스트 실패.
        //
        // 교재는 if (oq.isPresent()) { assertEquals(...) } 로 쓰는데, 값이 없으면 검사를 건너뛰어
        // 테스트가 "통과"해 버린다(가짜 초록불). orElseThrow() 는 데이터가 없을 때 확실히 실패시킨다.
        // (강사는 16강에서 .get() 으로 바꾸는데, 동작은 같지만 orElseThrow() 가 "값이 꼭 있어야 한다"는 의도를 더 분명히 드러낸다.)
        //
        // findById(1) → SELECT ... WHERE id = 1.
        // There might be no result, so instead of null it returns an Optional (a box that is either full or empty).
        // orElseThrow(): takes the value out if the box is full; throws NoSuchElementException if empty → the test fails.
        //
        // The book writes if (oq.isPresent()) { assertEquals(...) }, which skips the check when the value is missing,
        // so the test "passes" anyway (a false green). orElseThrow() makes it fail for sure when the data is missing.
        // (The instructor switches to .get() in lecture 16. It behaves the same, but orElseThrow() states the intent "a value must be here" more clearly.)
        //
        // id 가 1 인 이유: 테스트 DB는 매번 새로 만들어지고, TestInitData 가 이 질문을 가장 먼저 저장하기 때문.
        // Why id 1: the test database is fresh every run, and TestInitData saves this question first.
        Question question = questionRepository.findById(1).orElseThrow();

        assertThat(question.getSubject()).isEqualTo("sbb가 무엇인가요?");
    }

    @Test
    @DisplayName("findBySubject: 제목으로 질문을 조회한다")
    void t3() {
        // SELECT ... FROM question WHERE subject = 'sbb가 무엇인가요?'
        Question question = questionRepository.findBySubject("sbb가 무엇인가요?").orElseThrow();

        // 제목으로 찾은 질문이 1번 질문인지 확인한다.
        // Checks that the question found by subject is question 1.
        assertThat(question.getId()).isEqualTo(1);
    }

    @Test
    @DisplayName("findBySubjectAndContent: 제목과 내용이 모두 일치하는 질문을 조회한다")
    void t4() {
        // SELECT ... FROM question WHERE subject = 'sbb가 무엇인가요?' AND content = 'sbb에 대해서 알고 싶습니다.'
        Question question = questionRepository
                .findBySubjectAndContent("sbb가 무엇인가요?", "sbb에 대해서 알고 싶습니다.")
                .orElseThrow();

        assertThat(question.getId()).isEqualTo(1);
    }

    @Test
    @DisplayName("findBySubjectLike: 제목이 sbb로 시작하는 질문들을 조회한다")
    void t5() {
        // SELECT ... FROM question WHERE subject LIKE 'sbb%'
        // 샘플 질문 2개 중 "sbb가 무엇인가요?" 만 sbb 로 시작한다 ("스프링부트 모델 질문입니다." 는 아님).
        // Of the 2 sample questions, only "sbb가 무엇인가요?" starts with sbb ("스프링부트 모델 질문입니다." doesn't).
        List<Question> questions = questionRepository.findBySubjectLike("sbb%");

        // 교재·강사는 첫 번째 결과의 제목만 확인하지만, 개수도 검사해야 "다른 질문은 걸러졌다"는 것까지 보장된다.
        // The book and instructor only check the first result's subject; checking the size too proves the other question was filtered out.
        assertThat(questions).hasSize(1);
        assertThat(questions.get(0).getSubject()).isEqualTo("sbb가 무엇인가요?");
    }

    @Test
    @DisplayName("수정: 질문 제목을 바꾸고 저장한다")
    // 클래스의 @Transactional 덕분에 이 테스트에서 바꾼 데이터는 끝나면 롤백된다.
    // 006-02 의 TestInitData 에서는 "성공하면 커밋"이었지만, 테스트에서는 스프링이 기본으로 롤백한다.
    // 롤백이 없으면 질문 1번의 제목이 "수정된 제목"으로 남아서, 뒤에 실행되는 다른 테스트들이 모두 실패한다 (008-01 에서 직접 확인).
    // Thanks to the class-level @Transactional, whatever this test changes is rolled back when it ends.
    // In TestInitData (006-02) it meant "commit on success", but in tests Spring rolls back by default.
    // Without the rollback, question 1 keeps the subject "수정된 제목" and every test that runs afterwards fails (seen in 008-01).
    void t6() {
        Question question = questionRepository.findById(1).orElseThrow();

        // 자바 객체의 값을 바꾼다. 아직 DB는 그대로다.
        // Change the value on the Java object. The database is unchanged so far.
        question.setSubject("수정된 제목");

        // save: 이 객체는 이미 id(1)가 있으므로 INSERT 가 아니라 UPDATE 를 실행한다.
        // save: this object already has an id (1), so it runs UPDATE instead of INSERT.
        questionRepository.save(question);

        // 바뀐 제목으로 다시 찾으면 같은 1번 질문이 나와야 한다.
        // (강사는 .get() 뒤에 isNotNull() 로 확인하는데, .get() 은 값이 없으면 이미 예외를 던지므로 isNotNull() 은 절대 실패하지 않는다.
        //  대신 찾은 질문의 id 가 1 인지 확인한다.)
        // Searching by the new subject must return the same question 1.
        // (The instructor checks isNotNull() after .get(), but .get() already throws when empty, so isNotNull() can never fail.
        //  We check that the found question's id is 1 instead.)
        Question foundQuestion = questionRepository.findBySubject("수정된 제목").orElseThrow();
        assertThat(foundQuestion.getId()).isEqualTo(1);
    }

    @Test
    @DisplayName("삭제: 질문 1번을 삭제하면 개수가 2 → 1 로 줄어든다")
    // 삭제도 데이터를 바꾸지만, 클래스의 @Transactional 로 테스트가 끝나면 롤백된다 (t6 와 같은 이유).
    // Deleting also changes data, but the class-level @Transactional rolls it back when the test ends (same reason as t6).
    void t7() {
        // 삭제 전: 샘플 질문 2개. count() → SELECT COUNT(*) FROM question
        // Before deleting: 2 sample questions. count() → SELECT COUNT(*) FROM question
        assertThat(questionRepository.count()).isEqualTo(2);

        // delete → DELETE FROM question WHERE id = ?
        // Question 의 answers 에 cascade = REMOVE 가 있어서, 답변이 있었다면 답변도 함께 지워진다 (지금 샘플에는 답변이 없다).
        // delete → DELETE FROM question WHERE id = ?
        // Question.answers has cascade = REMOVE, so any answers would be deleted too (the sample data has no answers yet).
        Question question = questionRepository.findById(1).orElseThrow();
        questionRepository.delete(question);

        // 삭제 후: 1개만 남아야 한다.
        // After deleting: only 1 must remain.
        assertThat(questionRepository.count()).isEqualTo(1);
    }

    @Test
    @DisplayName("답변 생성: answerRepository 로 2번 질문에 답변을 저장한다")
    void t8() {
        Question question = questionRepository.findById(2).orElseThrow();

        Answer answer = new Answer();
        answer.setContent("네 자동으로 생성됩니다.");
        // 어떤 질문의 답변인지 연결한다. DB에는 question_id = 2 로 저장된다 (004-02 의 외래 키).
        // Link the answer to its question. The database stores question_id = 2 (the foreign key from 004-02).
        answer.setQuestion(question);
        answer.setCreateDate(LocalDateTime.now());
        // → INSERT INTO answer (content, create_date, question_id) VALUES (?, ?, ?)
        answerRepository.save(answer);

        // 저장되면 DB가 매긴 번호가 id 에 들어간다 (0 이 아니게 된다).
        // Once saved, the number the database assigned is put into id (it's no longer 0).
        assertThat(answer.getId()).isGreaterThan(0);
        assertThat(answer.getQuestion().getId()).isEqualTo(2);
    }

    @Test
    @DisplayName("답변 생성 by oneToMany: question.addAnswer 로 답변을 추가한다")
    void t9() {
        Question question = questionRepository.findById(2).orElseThrow();
        int beforeCount = question.getAnswers().size();

        Answer newAnswer = question.addAnswer("네 자동으로 생성됩니다.");

        // 아직 DB에 INSERT 되기 전이라 id 는 int 기본값 0 이다. 목록에는 이미 들어가 있다.
        // Not INSERTed yet, so id is still the int default 0. It's already in the Java list, though.
        assertThat(newAnswer.getId()).isEqualTo(0);
        assertThat(question.getAnswers()).hasSize(beforeCount + 1);

        // flush(): 지금까지 바뀐 내용을 DB에 바로 보낸다. cascade = PERSIST 덕분에 새 답변이 INSERT 되고 id 가 생긴다.
        // (트랜잭션 끝의 롤백으로 결국 취소된다.)
        // flush(): sends the pending changes to the database now. Thanks to cascade = PERSIST the new answer is INSERTed and gets an id.
        // (It's still undone by the rollback at the end of the test.)
        questionRepository.flush();
        assertThat(newAnswer.getId()).isGreaterThan(0);
    }

    @Test
    @DisplayName("답변 조회: answerRepository.findById(1)")
    void t10() {
        Answer answer = answerRepository.findById(1).orElseThrow();

        assertThat(answer.getContent()).isEqualTo("네 자동으로 생성됩니다.");
    }

    @Test
    @DisplayName("답변 조회 by oneToMany: question.getAnswers()")
    void t11() {
        Question question = questionRepository.findById(2).orElseThrow();

        // @OneToMany 는 기본이 LAZY(지연 로딩): 질문을 꺼낼 때 답변은 아직 DB에서 읽지 않고,
        // answers 를 처음 실제로 사용하는 순간 SELECT 를 실행한다. 그때 DB 연결(트랜잭션)이 살아 있어야 한다.
        // @OneToMany is LAZY by default: loading the question doesn't read its answers yet;
        // the SELECT runs the first time answers is actually used. The database connection (transaction) must still be open then.
        List<Answer> answers = question.getAnswers();

        assertThat(answers).hasSize(1);
        assertThat(answers.get(0).getContent()).isEqualTo("네 자동으로 생성됩니다.");
    }
}
